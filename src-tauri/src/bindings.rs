/// The scenarios the e2e specs and the mock rely on exist and are shaped as promised.
#[test]
fn scenarios_cover_what_the_ui_needs() {
    let g = record_scenarios();
    let snapshots: Vec<&Value> = g.nodes.values().map(|n| &n["snapshot"]).collect();
    assert!(
        snapshots
            .iter()
            .any(|s| s["view"]["no_voicing"].is_object()),
        "a no-voicing state exists"
    );
    assert!(
        snapshots
            .iter()
            .any(|s| s["view"]["mirrored"] == json!(true))
    );
    assert!(snapshots.iter().any(|s| s["view"]["capo"] == json!(5)));
    assert!(
        snapshots
            .iter()
            .any(|s| s["panel"]["chord_status"]["kind"] == json!("Error")),
        "the Hm7 state exists"
    );
    // c-voicings-cycle: at least 20 distinct steps with a wrap (edges revisit a node).
    let cycle_edges = g
        .edges
        .values()
        .flat_map(|m| m.keys())
        .filter(|k| k.starts_with("cycle|{\"action\":\"VoicingNext\"}"))
        .count();
    assert!(cycle_edges >= 8, "{cycle_edges} voicing steps recorded");
    assert!(
        g.nodes.len() > 60 && g.nodes.len() < 400,
        "{} nodes",
        g.nodes.len()
    );
}
