const HEADER: &str = "// GENERATED by `make bindings` (src-tauri/src/bindings.rs). Do not edit.\n";

fn ui_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../ui")
}

fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in name.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn type_names(spec: &CommandSpec) -> Vec<String> {
    let mut names = Vec::new();
    let texts = spec
        .args
        .iter()
        .map(|a| a.ts)
        .chain(std::iter::once(spec.returns));
    for text in texts {
        for word in text.split(|c: char| !c.is_alphanumeric()) {
            if word.chars().next().is_some_and(char::is_uppercase) {
                names.push(word.to_owned());
            }
        }
    }
    names
}

/// The text of `commands.ts`.
fn commands_ts() -> String {
    let mut imports: Vec<String> = COMMANDS.iter().flat_map(type_names).collect();
    imports.extend(["AppInfo".into()]);
    imports.sort();
    imports.dedup();
    let mut out = String::from(HEADER);
    for name in &imports {
        out.push_str(&format!("import type {{ {name} }} from './{name}';\n"));
    }
    out.push_str(
        "\n/** Every call from the UI into the Rust core: one method per Tauri command. */\n",
    );
    out.push_str("export interface Commands {\n");
    for c in COMMANDS {
        let params: Vec<String> = c
            .args
            .iter()
            .map(|a| {
                format!(
                    "{}{}: {}",
                    a.name,
                    if a.optional { "?" } else { "" },
                    if a.optional {
                        format!("{} | null", a.ts)
                    } else {
                        a.ts.to_owned()
                    }
                )
            })
            .collect();
        out.push_str(&format!(
            "  {}: ({}) => Promise<{}>;\n",
            camel(c.name),
            params.join(", "),
            c.returns
        ));
    }
    out.push_str("}\n\n");
    out.push_str("/** What `invoke` looks like to the generated wrappers. */\n");
    out.push_str(
        "export type Call = <T>(name: string, args?: Record<string, unknown>) => Promise<T>;\n\n",
    );
    out.push_str(
        "/** Builds the typed command layer on top of a `call` function (Tauri `invoke`). */\n",
    );
    out.push_str("export function createCommands(call: Call): Commands {\n  return {\n");
    for c in COMMANDS {
        let params: Vec<String> = c
            .args
            .iter()
            .map(|a| format!("{}{}", a.name, if a.optional { "?" } else { "" }))
            .collect();
        let args: Vec<String> = c
            .args
            .iter()
            .map(|a| {
                if a.optional {
                    format!("{}: {} ?? null", a.name, a.name)
                } else {
                    a.name.to_owned()
                }
            })
            .collect();
        let body = if args.is_empty() {
            format!("call<{}>('{}')", c.returns, c.name)
        } else {
            format!(
                "call<{}>('{}', {{ {} }})",
                c.returns,
                c.name,
                args.join(", ")
            )
        };
        out.push_str(&format!(
            "    {}: ({}) => {},\n",
            camel(c.name),
            params.join(", "),
            body
        ));
    }
    out.push_str("  };\n}\n\n");
    out.push_str("/** Every command name, as Rust registers it. */\n");
    out.push_str("export const COMMAND_NAMES = [\n");
    for c in COMMANDS {
        out.push_str(&format!("  '{}',\n", c.name));
    }
    out.push_str("] as const;\n");
    out
}

fn events_ts() -> String {
    format!(
        "{HEADER}import {{ listen, type UnlistenFn }} from '@tauri-apps/api/event';\nimport type {{ TunerReading }} from './TunerReading';\n\n/** The event the analysis thread emits at about 30 Hz while the tuner runs. */\nexport const TUNER_READING_EVENT = '{}';\n\n/** Subscribes to tuner readings; call the returned function to unsubscribe. */\nexport function listenTunerReading(handler: (reading: TunerReading) => void): Promise<UnlistenFn> {{\n  return listen<TunerReading>(TUNER_READING_EVENT, (event) => {{\n    handler(event.payload);\n  }});\n}}\n",
        crate::commands::TUNER_READING_EVENT
    )
}

/// JSON with sorted keys and no spaces; the TypeScript mock builds the same text.
fn canon(v: &Value) -> String {
    match v {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let parts: Vec<String> = keys
                .iter()
                .map(|k| format!("{}:{}", Value::String((*k).clone()), canon(&map[*k])))
                .collect();
            format!("{{{}}}", parts.join(","))
        }
        Value::Array(items) => {
            let parts: Vec<String> = items.iter().map(canon).collect();
            format!("[{}]", parts.join(","))
        }
        other => other.to_string(),
    }
}

fn fnv(text: &str) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in text.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{hash:012x}")[..12].to_owned()
}

#[derive(Default)]
struct Graph {
    start: String,
    nodes: BTreeMap<String, Value>,
    edges: BTreeMap<String, BTreeMap<String, String>>,
    parse: BTreeMap<String, Value>,
    tuner_targets: Value,
}

struct Recorder<'a> {
    graph: &'a mut Graph,
    state: AppState,
    current: String,
    _dir: tempfile::TempDir,
}

fn node_id(snapshot: &ExplorerSnapshot, settings: &Value) -> String {
    let key = json!([
        snapshot.panel.selection,
        snapshot.panel.instrument,
        snapshot.panel.chord_status,
        snapshot.panel.chord_text,
        settings
    ]);
    fnv(&canon(&key))
}

impl<'a> Recorder<'a> {
    fn new(graph: &'a mut Graph) -> Self {
        let dir = tempfile::tempdir().expect("temp dir");
        let state = AppState::new(dir.path().to_path_buf(), Box::new(FakeAudio::default()));
        let mut rec = Self {
            graph,
            state,
            current: String::new(),
            _dir: dir,
        };
        let id = rec.record_node();
        if rec.graph.start.is_empty() {
            rec.graph.start = id.clone();
        }
        assert_eq!(
            rec.graph.start, id,
            "every scenario starts at the default state"
        );
        rec.current = id;
        rec
    }

    fn record_node(&mut self) -> String {
        let snapshot = self.state.get_snapshot(None).expect("snapshot");
        let settings = serde_json::to_value(self.state.get_settings().expect("settings"))
            .expect("settings json");
        let id = node_id(&snapshot, &settings);
        // The revision is the mock's own counter: store 0 so the file does not churn.
        let mut value = serde_json::to_value(&snapshot).expect("snapshot json");
        value["revision"] = json!(0);
        value["notices"] = snapshot_notices(&value);
        self.graph
            .nodes
            .entry(id.clone())
            .or_insert_with(|| json!({ "snapshot": value, "settings": settings }));
        id
    }

    /// Records the edge from the current node for the command just run.
    fn edge(&mut self, name: &str, args: &Value) {
        let to = self.record_node();
        let key = format!("{name}|{}", canon(args));
        self.graph
            .edges
            .entry(self.current.clone())
            .or_default()
            .insert(key, to.clone());
        self.current = to;
    }

    fn chord(&mut self, text: &str) -> &mut Self {
        let args = json!({ "text": text });
        self.state.select_chord(text, None).expect("select_chord");
        self.edge("select_chord", &args);
        self
    }

    fn diatonic(&mut self, n: u8) -> &mut Self {
        let degree = Degree::new(n).expect("degree");
        self.state
            .select_diatonic_chord(degree, None)
            .expect("diatonic");
        self.edge("select_diatonic_chord", &json!({ "degree": degree }));
        self
    }

    fn cycle(&mut self, action: CycleAction) -> &mut Self {
        self.state.cycle(action, None).expect("cycle");
        self.edge("cycle", &json!({ "action": action }));
        self
    }

    fn cycles(&mut self, action: CycleAction, n: usize) -> &mut Self {
        for _ in 0..n {
            self.cycle(action);
        }
        self
    }

    fn view(&mut self, view: ViewType) -> &mut Self {
        self.state.set_view_type(view, None).expect("view");
        self.edge("set_view_type", &json!({ "view": view }));
        self
    }

    fn key(&mut self, tonic: &str, mode: Mode) -> &mut Self {
        let tonic: Note = tonic.parse().expect("note");
        self.state.select_key(tonic, mode, None).expect("key");
        self.edge("select_key", &json!({ "tonic": tonic, "mode": mode }));
        self
    }

    fn capo(&mut self, capo: u8) -> &mut Self {
        self.state.set_capo(capo, None).expect("capo");
        self.edge("set_capo", &json!({ "capo": capo }));
        self
    }

    fn tuning(&mut self, tuning: TuningChoice) -> &mut Self {
        self.state
            .select_tuning(tuning.clone(), None)
            .expect("tuning");
        self.edge("select_tuning", &json!({ "tuning": tuning }));
        self
    }

    fn option(&mut self, option: ExplorerOption) -> &mut Self {
        self.state.set_option(option, None).expect("option");
        self.edge("set_option", &json!({ "option": option }));
        self
    }

    fn labels(&mut self, labels: LabelsMode) -> &mut Self {
        self.state.set_labels_mode(labels, None).expect("labels");
        self.edge("set_labels_mode", &json!({ "labels": labels }));
        self
    }

    fn overlay(&mut self, overlay: OverlayRequest) -> &mut Self {
        self.state
            .set_scale_overlay(overlay, None)
            .expect("overlay");
        self.edge("set_scale_overlay", &json!({ "overlay": overlay }));
        self
    }

    fn note(&mut self, string: u8, fret: u8) -> &mut Self {
        self.state.select_note(string, fret, None).expect("note");
        self.edge("select_note", &json!({ "string": string, "fret": fret }));
        self
    }

    fn settings(&mut self, patch: SettingsPatch) -> &mut Self {
        self.state.set_settings(patch.clone()).expect("settings");
        self.edge("set_settings", &json!({ "patch": patch }));
        self
    }
}

fn snapshot_notices(value: &Value) -> Value {
    value["notices"].clone()
}

fn left_handed(on: bool, flip: bool) -> SettingsPatch {
    let mut instrument = InstrumentSettings::default();
    instrument.handedness.left_handed = on;
    instrument.handedness.flip_strings = flip;
    SettingsPatch {
        instrument: Some(instrument),
        ..SettingsPatch::default()
    }
}

/// Drives the real core through every scripted scenario.
fn record_scenarios() -> Graph {
    use CycleAction as C;
    let mut graph = Graph::default();

    // g-major-notes: the start state itself, plus its relatives and circle-of-fifths walk.
    {
        let mut r = Recorder::new(&mut graph);
        r.cycles(C::KeyNext, 12)
            .cycles(C::KeyPrev, 12)
            .cycle(C::RelativeToggle)
            .cycle(C::RelativeToggle);
        r.key("D", Mode::Major)
            .key("G", Mode::Major)
            .key("G", Mode::Dorian)
            .key("G", Mode::Major);
        r.cycle(C::CycleLabels)
            .cycle(C::CycleLabels)
            .cycle(C::CycleLabels);
        r.labels(LabelsMode::ScaleDegree)
            .labels(LabelsMode::NoteName);
        r.cycle(C::ToggleOverlay).cycle(C::ToggleOverlay);
        r.note(3, 0).cycle(C::ClearFocus);
        r.note(1, 3).cycle(C::ClearFocus);
    }
    // chord-field-error: a misspelt chord from the start state, then the suggested fix.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("Hm7").chord("Bm7");
    }
    // chord-strip-walk: I to vii, then ChordNext/ChordPrev around the strip, sevenths on.
    {
        let mut r = Recorder::new(&mut graph);
        for n in 1..=7 {
            r.diatonic(n);
        }
        r.cycle(C::ClearFocus);
        r.cycles(C::ChordNext, 8)
            .cycles(C::ChordPrev, 3)
            .cycle(C::ClearFocus);
        r.cycles(C::ChordPrev, 2).cycle(C::ClearFocus);
        r.option(ExplorerOption::ShowSevenths(true));
        for n in 1..=7 {
            r.diatonic(n);
        }
        r.option(ExplorerOption::ShowSevenths(false));
    }
    // c-voicings-cycle: C by text, voicing view, 26 steps forward (wraps), back, labels.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("C").view(ViewType::Voicing);
        r.cycles(C::VoicingNext, 30).cycles(C::VoicingPrev, 3);
        r.cycle(C::CycleLabels)
            .cycle(C::CycleLabels)
            .cycle(C::CycleLabels)
            .cycle(C::CycleLabels);
        r.cycles(C::CycleView, 4)
            .cycle(C::ChordNext)
            .cycle(C::ChordPrev);
        r.view(ViewType::AllTones).view(ViewType::Voicing);
        r.chord("F").cycles(C::VoicingNext, 6);
        r.chord("vi").chord("Hm7").chord("Bm7");
    }
    // triads-234-cycle: C triad, string sets, inversions, positions, show all on the set.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("C").view(ViewType::Triad);
        r.cycles(C::StringSetNext, 5).cycles(C::StringSetPrev, 5);
        r.cycles(C::InversionNext, 4).cycles(C::InversionPrev, 3);
        r.cycles(C::PositionNext, 4).cycles(C::PositionPrev, 4);
        r.option(ExplorerOption::ShowAllOnSet(true))
            .option(ExplorerOption::ShowAllOnSet(false));
        r.chord("G7").cycle(C::InversionNext);
    }
    // am-arpeggio-position-5: Am arpeggio in positions, show order, direction.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("Am").view(ViewType::Arpeggio);
        r.cycles(C::PositionNext, 8).cycles(C::PositionPrev, 8);
        r.option(ExplorerOption::ShowOrder(true));
        r.option(ExplorerOption::ArpeggioDirection(ArpeggioDirection::Down));
        r.option(ExplorerOption::ArpeggioDirection(ArpeggioDirection::Up));
        r.option(ExplorerOption::ShowOrder(false));
    }
    // a-minor-pent-boxes: A minor, pentatonic overlay and its boxes.
    {
        let mut r = Recorder::new(&mut graph);
        r.key("A", Mode::NaturalMinor);
        let scale = Scale {
            tonic: "A".parse().expect("note"),
            mode: Mode::MinorPentatonic,
        };
        r.overlay(OverlayRequest {
            on: true,
            scale: Some(scale),
            follow: false,
        });
        r.cycles(C::PositionNext, 7).cycles(C::PositionPrev, 2);
        r.overlay(OverlayRequest {
            on: false,
            scale: Some(scale),
            follow: false,
        });
        r.chord("Am")
            .cycle(C::ToggleOverlay)
            .cycle(C::ToggleOverlay);
    }
    // left-handed-g: handedness from the settings screen.
    {
        let mut r = Recorder::new(&mut graph);
        r.settings(left_handed(true, false));
        r.settings(left_handed(true, true));
        r.settings(left_handed(false, true));
        r.settings(left_handed(false, false));
        r.chord("C").view(ViewType::Voicing);
        r.settings(left_handed(true, false));
        r.settings(left_handed(false, false));
    }
    // capo-5-moved: capo with a chord, back to no capo, a shape under capo.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("G").view(ViewType::Voicing).capo(2).capo(0);
        r.chord("Am")
            .view(ViewType::Arpeggio)
            .cycle(C::PositionNext)
            .capo(5)
            .capo(0);
        r.cycle(C::ClearFocus).capo(3).capo(0);
        r.note(2, 1);
    }
    // tunings: presets with a chord, and a custom tuning with a warning.
    {
        let mut r = Recorder::new(&mut graph);
        r.chord("D").view(ViewType::Voicing);
        r.tuning(TuningChoice::Preset(TuningPreset::DropD));
        r.tuning(TuningChoice::Preset(TuningPreset::Dadgad));
        r.tuning(TuningChoice::Preset(TuningPreset::Standard));
        let custom = vec!["F#3", "A2", "D3", "G3", "B3", "E4"]
            .into_iter()
            .map(String::from)
            .collect();
        r.tuning(TuningChoice::Custom(custom));
        r.tuning(TuningChoice::Preset(TuningPreset::Standard));
    }
    // no-voicing: a tuning where a chord has no playable voicing, and both relax buttons.
    {
        let mut r = Recorder::new(&mut graph);
        let same: Vec<String> = vec!["C2"; 6].into_iter().map(String::from).collect();
        r.tuning(TuningChoice::Custom(same));
        r.chord("C#dim7").view(ViewType::Voicing);
        r.option(ExplorerOption::AllowStretch(true));
        r.option(ExplorerOption::AllowOmittedFifth(true));
        r.option(ExplorerOption::AllowStretch(false));
        r.option(ExplorerOption::AllowOmittedFifth(false));
    }
    // parse outcomes for the live chord field.
    {
        let state_dir = tempfile::tempdir().expect("temp dir");
        let state = AppState::new(
            state_dir.path().to_path_buf(),
            Box::new(FakeAudio::default()),
        );
        for text in ["Hm7", "Bm7", "C", "Am", "vi", "G7", "Cmaj7", "x"] {
            let outcome = state.parse_chord(text).expect("parse");
            graph.parse.insert(
                text.to_owned(),
                serde_json::to_value(outcome).expect("json"),
            );
        }
    }
    // The tuner's target strings for the default instrument (the mock tuner shows these).
    {
        let dir = tempfile::tempdir().expect("temp dir");
        let state = AppState::new(dir.path().to_path_buf(), Box::new(FakeAudio::default()));
        let info = state
            .tuner_start(
                None,
                std::sync::Arc::new(|_: &mackey_audio::dsp::TunerReading| {}),
            )
            .expect("tuner start");
        graph.tuner_targets = serde_json::to_value(info.targets).expect("json");
    }
    graph
}

fn scenarios_json(graph: &Graph) -> String {
    let nodes: serde_json::Map<String, Value> = graph
        .nodes
        .iter()
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    let edges: serde_json::Map<String, Value> = graph
        .edges
        .iter()
        .map(|(from, map)| (from.clone(), json!(map)))
        .collect();
    let value = json!({
        "start": graph.start,
        "nodes": nodes,
        "edges": edges,
        "parse": graph.parse,
        "tuner_targets": graph.tuner_targets,
    });
    serde_json::to_string(&value).expect("json")
}

fn write_if_changed(path: &std::path::Path, text: &str) {
    if std::fs::read_to_string(path).ok().as_deref() != Some(text) {
        std::fs::create_dir_all(path.parent().expect("parent")).expect("create dir");
        std::fs::write(path, text).expect("write generated file");
    }
}

/// Writes `commands.ts`, `events.ts` and the scenarios; running it twice gives identical bytes.
#[test]
fn export_bindings_commands_events_and_scenarios() {
    let ui = ui_dir();
    write_if_changed(&ui.join("src/bindings/commands.ts"), &commands_ts());
    write_if_changed(&ui.join("src/bindings/events.ts"), &events_ts());
    let graph = record_scenarios();
    let text = scenarios_json(&graph);
    // Determinism: a second recording is byte-identical.
    assert_eq!(text, scenarios_json(&record_scenarios()));
    write_if_changed(&ui.join("src/mocks/scenarios.json"), &text);
}

