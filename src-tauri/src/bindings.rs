//! Generators for the UI bindings, run as tests by `make bindings` (their names start with
//! `export_bindings`): the typed command wrappers (`commands.ts`), the event helper
//! (`events.ts`) and the recorded scenarios the mock command layer replays
//! (`ui/src/mocks/scenarios.json`).
//!
//! The scenarios are produced by driving the real `AppState` through scripted action
//! sequences, so the mocked UI shows real voicings and the UI never needs theory (ADR 0007).

// This module is test-only code generation: text assembly with format! and a long scripted
// recorder read better than the lints' preferred forms.
#![allow(
    clippy::format_push_string,
    clippy::needless_pass_by_value,
    clippy::too_many_lines
)]

